// Pure helpers for the release flow: reading Conventional Commits, picking the
// next version and writing the changelog. No git or file access lives here, so
// everything can be unit tested (see release-lib.test.mjs).

const TYPES = /^(\w+)(?:\(([^)]+)\))?(!)?:\s*(.+)$/;

/** Parses one commit. Subjects without a `type:` prefix are type "other". */
export function parseCommit({ subject, body = "" }) {
  const m = TYPES.exec(subject.trim());
  const breakingFooter = /^BREAKING[ -]CHANGE:/m.test(body);
  if (!m) {
    return {
      type: "other",
      scope: "",
      breaking: breakingFooter,
      text: subject.trim(),
    };
  }
  return {
    type: m[1].toLowerCase(),
    scope: m[2] ?? "",
    breaking: m[3] === "!" || breakingFooter,
    text: m[4].trim(),
  };
}

/** Commits that never belong in a release: the bot's own and CI bookkeeping. */
export function isNoise(subject) {
  return (
    /^chore\(release\):/i.test(subject) ||
    /^update visual baselines$/i.test(subject)
  );
}

const LEVELS = { patch: 1, minor: 2, major: 3 };

/**
 * The bump the commits ask for, or null when none of them is user facing.
 * Below 1.0 a breaking change bumps the minor, because 0.x has no stable API.
 */
export function decideBump(commits, version) {
  const preStable = parseVersion(version).major === 0;
  let level = 0;
  for (const c of commits) {
    let l = 0;
    if (c.breaking) l = preStable ? LEVELS.minor : LEVELS.major;
    else if (c.type === "feat") l = LEVELS.minor;
    else if (c.type === "fix" || c.type === "perf") l = LEVELS.patch;
    level = Math.max(level, l);
  }
  return level === 0 ? null : Object.keys(LEVELS)[level - 1];
}

export function parseVersion(v) {
  const m = /^v?(\d+)\.(\d+)\.(\d+)$/.exec(v.trim());
  if (!m) throw new Error(`Not a version: ${v}`);
  return { major: Number(m[1]), minor: Number(m[2]), patch: Number(m[3]) };
}

export function bumpVersion(version, level) {
  const { major, minor, patch } = parseVersion(version);
  if (level === "major") return `${major + 1}.0.0`;
  if (level === "minor") return `${major}.${minor + 1}.0`;
  if (level === "patch") return `${major}.${minor}.${patch + 1}`;
  throw new Error(`Unknown bump: ${level}`);
}

const SECTIONS = [
  ["Breaking changes", (c) => c.breaking],
  ["Features", (c) => c.type === "feat"],
  ["Fixes", (c) => c.type === "fix" || c.type === "perf"],
  ["Maintenance", () => true],
];

function line(c) {
  const scope = c.scope ? `**${c.scope}:** ` : "";
  return `- ${scope}${c.text}`;
}

/** One `## vX.Y.Z (date)` block, grouped by kind. Each commit appears once. */
export function changelogEntry(version, date, commits) {
  const left = [...commits];
  const out = [`## v${version} (${date})`, ""];
  for (const [title, test] of SECTIONS) {
    const mine = left.filter(test);
    if (mine.length === 0) continue;
    for (const c of mine) left.splice(left.indexOf(c), 1);
    out.push(`### ${title}`, "", ...mine.map(line), "");
  }
  return out.join("\n");
}

const HEADER =
  "# Changelog\n\nAll notable changes to Fogtrail. Generated by `npm run release`.\n";

/** Puts a new entry right under the title, keeping older ones. */
export function prependChangelog(existing, entry) {
  const body =
    existing && existing.trim() !== ""
      ? existing.replace(/^# Changelog[\s\S]*?\n(?=## )/, "")
      : "";
  const rest = body.startsWith("## ") ? body : "";
  return (
    `${HEADER}\n${entry}\n${rest}`.replace(/\n{3,}/g, "\n\n").trimEnd() + "\n"
  );
}

/** The text of one version's section, for the release notes. */
export function sectionFor(changelog, version) {
  const lines = changelog.split("\n");
  const start = lines.findIndex(
    (l) => l.startsWith(`## v${version} `) || l === `## v${version}`,
  );
  if (start === -1) return "";
  let end = lines.findIndex((l, i) => i > start && l.startsWith("## "));
  if (end === -1) end = lines.length;
  return lines
    .slice(start + 1, end)
    .join("\n")
    .trim();
}

/** Replaces the app version in each file's text, leaving its formatting alone. */
export function writeVersion(files, version) {
  const first = (text, re, name) => {
    if (!re.test(text)) throw new Error(`No version found in ${name}`);
    return text.replace(re, `$1${version}`);
  };
  const out = { ...files };
  out["package.json"] = first(
    files["package.json"],
    /("version":\s*")[^"]+/,
    "package.json",
  );
  out["src-tauri/tauri.conf.json"] = first(
    files["src-tauri/tauri.conf.json"],
    /("version":\s*")[^"]+/,
    "tauri.conf.json",
  );
  out["src-tauri/Cargo.toml"] = first(
    files["src-tauri/Cargo.toml"],
    /^(version\s*=\s*")[^"]+/m,
    "Cargo.toml",
  );
  out["src-tauri/Cargo.lock"] = first(
    files["src-tauri/Cargo.lock"],
    /(name = "fogtrail"\nversion = ")[^"]+/,
    "Cargo.lock",
  );
  const lock = JSON.parse(files["package-lock.json"]);
  lock.version = version;
  if (lock.packages?.[""]) lock.packages[""].version = version;
  out["package-lock.json"] = JSON.stringify(lock, null, 2) + "\n";
  return out;
}

