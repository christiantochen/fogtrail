import type { Page } from "@playwright/test";
import { expect, test } from "./fixtures";
import { box, choose, optionTexts } from "./dropdown";
import { stubBackend } from "./stub";

async function openShop(page: Page) {
  await stubBackend(page, [], { postgres: true });
  await page.goto("/");
  await page
    .locator(".card")
    .filter({ hasText: "shop-pg" })
    .getByRole("button", { name: "Connect", exact: true })
    .click();
  await page.getByRole("list", { name: "Tables" }).waitFor();
}

const table = (page: Page, name: string | RegExp) =>
  page.getByRole("list", { name: "Tables" }).getByRole("button", { name });

test.describe("browsing PostgreSQL", () => {
  test("opens the public schema and hides the system ones", async ({
    page,
  }) => {
    await openShop(page);
    await expect(box(page, "Schema")).toHaveAttribute("data-value", "public");
    expect(await optionTexts(page, "Schema")).toEqual(["billing", "public"]);
    await expect(table(page, /^orders/)).toContainText("~48k");
    await expect(page.getByLabel("Search keys")).toHaveCount(0);
    await expect(
      page.getByText("Read-only transaction. Writes blocked."),
    ).toBeVisible();
  });

  test("shows system schemas on request and switches schema", async ({
    page,
  }) => {
    await openShop(page);
    await page.getByRole("button", { name: "Show system schemas" }).click();
    expect(await optionTexts(page, "Schema")).toContain("pg_catalog");
    await choose(page, "Schema", "billing");
    await expect(table(page, /^invoices/)).toBeVisible();
  });

  test("views and materialized views are badged", async ({ page }) => {
    await openShop(page);
    await expect(table(page, /^paying_customers/)).toContainText("view");
    await expect(table(page, /^mv_plan_counts/)).toContainText("matview");
    await expect(table(page, /^Weird Name/)).toBeVisible();
  });

  test("rows show JSONB as a chip and keep the timestamp's offset", async ({
    page,
  }) => {
    await openShop(page);
    await table(page, /^orders/).click();
    const grid = page.getByRole("table", { name: "Rows of orders" });
    await expect(grid.getByText("{ } 2 keys")).toBeVisible();
    await expect(grid.getByRole("cell", { name: "184.50" })).toHaveClass(/num/);
    await expect(grid.getByRole("cell", { name: "NULL" })).toHaveCount(1);
    await expect(grid.getByRole("cell", { name: /2026-11-11/ })).toContainText(
      "09:42:07.5+00",
    );
  });

  test("Structure shows identity columns, a partial index and the foreign key", async ({
    page,
  }) => {
    await openShop(page);
    await table(page, /^orders/).click();
    await page.getByRole("tab", { name: "Structure" }).click();
    const cols = page.getByRole("table", { name: "Columns" });
    await expect(cols.getByRole("row", { name: /^id bigint/ })).toContainText(
      "generated by default as identity",
    );
    await expect(page.getByText("btree · partial")).toBeVisible();
    await expect(page.getByText("orders_customer_id_fkey")).toBeVisible();
    // PostgreSQL has no storage engine to show.
    await expect(page.getByText("Engine")).toHaveCount(0);
  });
});

test.describe("the PostgreSQL connection form", () => {
  async function newForm(page: Page) {
    await stubBackend(page);
    await page.goto("/");
    await page.getByRole("button", { name: "New connection" }).click();
    await page.getByRole("heading", { name: "New connection" }).waitFor();
    await page
      .getByRole("radiogroup", { name: "Data store" })
      .getByRole("radio", { name: "PostgreSQL" })
      .click();
  }
  const saved = (page: Page) =>
    page.evaluate(
      () =>
        (
          window as unknown as {
            __saved: { profile: Record<string, unknown> }[];
          }
        ).__saved,
    );

  test("choosing PostgreSQL sets the port, asks for a database and shows the role tip", async ({
    page,
  }) => {
    await newForm(page);
    await expect(page.getByLabel("Port")).toHaveValue("5432");
    await expect(page.getByLabel("Database", { exact: true })).toBeVisible();
    await expect(box(page, "SSL mode")).toHaveAttribute(
      "data-value",
      "require",
    );
    await page.getByLabel("User").fill("ro");
    await page.getByLabel("Database", { exact: true }).fill("shop");
    const tip = page.locator(".code--tip");
    await expect(tip).toContainText('CREATE ROLE "ro" LOGIN');
    await expect(tip).toContainText('GRANT CONNECT ON DATABASE "shop"');
  });

  test("pasting a postgres:// URL fills the form", async ({ page }) => {
    await newForm(page);
    await page.getByLabel("Host").focus();
    await page.evaluate(() => {
      const el = document.activeElement as HTMLInputElement;
      const data = new DataTransfer();
      data.setData(
        "text",
        "postgres://ro:pw@db.example.com:6432/shop?sslmode=verify-full",
      );
      el.dispatchEvent(
        new ClipboardEvent("paste", {
          clipboardData: data,
          bubbles: true,
          cancelable: true,
        }),
      );
    });
    await expect(page.getByLabel("Host")).toHaveValue("db.example.com");
    await expect(page.getByLabel("Port")).toHaveValue("6432");
    await expect(page.getByLabel("User")).toHaveValue("ro");
    await expect(page.getByLabel("Database", { exact: true })).toHaveValue(
      "shop",
    );
    await expect(box(page, "SSL mode")).toHaveAttribute(
      "data-value",
      "verify-full",
    );
  });

  test("a database is required, and the profile saves with its SSL mode", async ({
    page,
  }) => {
    await newForm(page);
    await page.getByLabel("Name").fill("pg");
    await page.getByLabel("User").fill("ro");
    await page.getByRole("button", { name: "Save", exact: true }).click();
    await expect(page.getByText("Enter a database.")).toBeVisible();
    // The message sits inside the label, so the name now starts with "Database".
    await page.getByLabel(/^Database/).fill("shop");
    await choose(page, "SSL mode", "disable");
    await page.getByRole("button", { name: "Save", exact: true }).click();
    await expect.poll(async () => (await saved(page))?.length).toBe(1);
    expect((await saved(page))[0].profile).toMatchObject({
      driver: "postgres",
      dbname: "shop",
      sslMode: "disable",
      tls: false,
      port: 5432,
    });
  });
});

test.describe("PostgreSQL values and indexes", () => {
  async function openOrders(page: Page) {
    await openShop(page);
    await table(page, /^orders/).click();
    await page.getByRole("table", { name: "Rows of orders" }).waitFor();
  }
  const grid = (page: Page) =>
    page.getByRole("table", { name: "Rows of orders" });

  test("a JSON chip opens that value, Esc goes back to the row, then closes", async ({
    page,
  }) => {
    await openOrders(page);
    await grid(page)
      .getByRole("button", { name: "Open items, 2 keys" })
      .click();
    const solo = page.getByRole("dialog", { name: "items" });
    await expect(
      solo.getByRole("button", { name: "Back to row" }),
    ).toBeVisible();
    await expect(solo.getByRole("tab", { name: "Formatted" })).toHaveAttribute(
      "aria-selected",
      "true",
    );
    await expect(solo).toContainText('"sku"');
    await page.keyboard.press("Escape");
    await expect(
      page.getByRole("dialog", { name: "Row details" }),
    ).toBeVisible();
    await page.keyboard.press("Escape");
    await expect(page.getByRole("dialog")).toHaveCount(0);
  });

  test("clicking the chip does not also open the row on its own", async ({
    page,
  }) => {
    await openOrders(page);
    await grid(page)
      .getByRole("button", { name: "Open items, 2 keys" })
      .click();
    await expect(page.getByRole("dialog", { name: "Row details" })).toHaveCount(
      0,
    );
  });

  test("Raw shows the value as the server sent it, and the choice is kept", async ({
    page,
  }) => {
    await openOrders(page);
    const chip = grid(page).getByRole("button", { name: "Open items, 2 keys" });
    await chip.click();
    const solo = page.getByRole("dialog", { name: "items" });
    await solo.getByRole("tab", { name: "Raw" }).click();
    await expect(solo.locator(".code--raw")).toHaveText(
      '{"sku": "BK-114", "qty": 2}',
    );
    await expect(solo.getByRole("button", { name: "Copy raw" })).toBeVisible();
    await page.keyboard.press("Escape");
    await page.keyboard.press("Escape");
    await chip.click();
    await expect(
      page
        .getByRole("dialog", { name: "items" })
        .getByRole("tab", { name: "Raw" }),
    ).toHaveAttribute("aria-selected", "true");
    // Formatted is one click away again.
    await page.getByRole("tab", { name: "Formatted" }).click();
    await expect(page.locator(".code--raw")).toHaveCount(0);
  });

  test("search works in the Raw view", async ({ page }) => {
    await openOrders(page);
    await grid(page)
      .getByRole("button", { name: "Open items, 2 keys" })
      .click();
    const solo = page.getByRole("dialog", { name: "items" });
    await solo.getByRole("tab", { name: "Raw" }).click();
    await solo.getByLabel("Find in value").fill("BK-114");
    await expect(solo.locator(".code--raw mark")).toHaveCount(1);
  });

  test("an array is a chip too, and opens as a list", async ({ page }) => {
    await openOrders(page);
    await grid(page)
      .getByRole("button", { name: "Open tags, 2 items" })
      .click();
    const solo = page.getByRole("dialog", { name: "tags" });
    await expect(solo).toContainText("rush order");
    await expect(solo.locator(".badge", { hasText: "array" })).toBeVisible();
    await solo.getByRole("tab", { name: "Raw" }).click();
    await expect(solo.locator(".code--raw")).toHaveText('{gift,"rush order"}');
  });

  test("a number JSON can't hold exactly gets a notice, gone in Raw", async ({
    page,
  }) => {
    await openOrders(page);
    await grid(page).getByRole("button", { name: "Open items, 1 key" }).click();
    const solo = page.getByRole("dialog", { name: "items" });
    await expect(solo.getByRole("status")).toContainText(
      "too big to show exactly",
    );
    await solo.getByRole("tab", { name: "Raw" }).click();
    await expect(solo.getByRole("status")).toHaveCount(0);
    await expect(solo.locator(".code--raw")).toContainText("9007199254740993");
  });

  test("a time with an offset also shows UTC in the row dialog", async ({
    page,
  }) => {
    const expand = () =>
      page.getByRole("button", { name: "Expand row in a dialog" });
    const dialog = () => page.getByRole("dialog", { name: "Row details" });
    await openOrders(page);
    await grid(page).locator("tbody tr").nth(2).locator("td").first().click();
    await expand().click();
    await expect(dialog()).toContainText("= 2026-11-09 05:18:42 UTC");
    // A time already in UTC says nothing extra.
    await page.keyboard.press("Escape");
    await grid(page).locator("tbody tr").nth(0).locator("td").first().click();
    await expand().click();
    await expect(dialog()).toContainText("09:42:07.5+00");
    await expect(dialog()).not.toContainText("= 2026");
  });

  test("Indexes is its own tab, and a click shows how an index is made", async ({
    page,
  }) => {
    await openOrders(page);
    await page.getByRole("tab", { name: "Indexes" }).click();
    const list = page.getByRole("table", { name: "Indexes" });
    await expect(
      list.getByRole("row", { name: /idx_orders_big/ }),
    ).toContainText("btree · partial");
    await expect(page.locator(".code--tip")).toHaveCount(0);
    await list.getByRole("button", { name: "idx_orders_big" }).click();
    await expect(page.locator(".code--tip")).toContainText(
      "CREATE INDEX idx_orders_big ON public.orders USING btree (total) WHERE (total > 1000)",
    );
    await list.getByRole("button", { name: "idx_orders_big" }).click();
    await expect(page.locator(".code--tip")).toHaveCount(0);
  });
});
