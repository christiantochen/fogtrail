import type { Page } from "@playwright/test";
import { expect, test } from "./fixtures";
import { box, choose, optionTexts } from "./dropdown";
import { stubBackend } from "./stub";

async function openShop(page: Page) {
  await stubBackend(page, [], { postgres: true });
  await page.goto("/");
  await page
    .locator(".card")
    .filter({ hasText: "shop-pg" })
    .getByRole("button", { name: "Connect", exact: true })
    .click();
  await page.getByRole("list", { name: "Tables" }).waitFor();
}

const table = (page: Page, name: string | RegExp) =>
  page.getByRole("list", { name: "Tables" }).getByRole("button", { name });

test.describe("browsing PostgreSQL", () => {
  test("opens the public schema and hides the system ones", async ({
    page,
  }) => {
    await openShop(page);
    await expect(box(page, "Schema")).toHaveAttribute("data-value", "public");
    expect(await optionTexts(page, "Schema")).toEqual(["billing", "public"]);
    await expect(table(page, /^orders/)).toContainText("~48k");
    await expect(page.getByLabel("Search keys")).toHaveCount(0);
    await expect(
      page.getByText("Read-only transaction. Writes blocked."),
    ).toBeVisible();
  });

  test("shows system schemas on request and switches schema", async ({
    page,
  }) => {
    await openShop(page);
    await page.getByRole("button", { name: "Show system schemas" }).click();
    expect(await optionTexts(page, "Schema")).toContain("pg_catalog");
    await choose(page, "Schema", "billing");
    await expect(table(page, /^invoices/)).toBeVisible();
  });

  test("views and materialized views are badged", async ({ page }) => {
    await openShop(page);
    await expect(table(page, /^paying_customers/)).toContainText("view");
    await expect(table(page, /^mv_plan_counts/)).toContainText("matview");
    await expect(table(page, /^Weird Name/)).toBeVisible();
  });

  test("rows show JSONB as a chip and keep the timestamp's offset", async ({
    page,
  }) => {
    await openShop(page);
    await table(page, /^orders/).click();
    const grid = page.getByRole("table", { name: "Rows of orders" });
    await expect(grid.getByText("{ } 2 keys")).toBeVisible();
    await expect(grid.getByRole("cell", { name: "184.50" })).toHaveClass(/num/);
    await expect(grid.getByRole("cell", { name: "NULL" })).toHaveCount(1);
    await expect(grid.getByRole("cell", { name: /2026-11-11/ })).toContainText(
      "09:42:07.5+00",
    );
  });

  test("Structure shows identity columns, a partial index and the foreign key", async ({
    page,
  }) => {
    await openShop(page);
    await table(page, /^orders/).click();
    await page.getByRole("tab", { name: "Structure" }).click();
    const cols = page.getByRole("table", { name: "Columns" });
    await expect(cols.getByRole("row", { name: /^id bigint/ })).toContainText(
      "generated by default as identity",
    );
    await expect(page.getByText("btree · partial")).toBeVisible();
    await expect(page.getByText("orders_customer_id_fkey")).toBeVisible();
    // PostgreSQL has no storage engine to show.
    await expect(page.getByText("Engine")).toHaveCount(0);
  });
});

test.describe("the PostgreSQL connection form", () => {
  async function newForm(page: Page) {
    await stubBackend(page);
    await page.goto("/");
    await page.getByRole("button", { name: "New connection" }).click();
    await page.getByRole("heading", { name: "New connection" }).waitFor();
    await page
      .getByRole("radiogroup", { name: "Data store" })
      .getByRole("radio", { name: "PostgreSQL" })
      .click();
  }
  const saved = (page: Page) =>
    page.evaluate(
      () =>
        (
          window as unknown as {
            __saved: { profile: Record<string, unknown> }[];
          }
        ).__saved,
    );

  test("choosing PostgreSQL sets the port, asks for a database and shows the role tip", async ({
    page,
  }) => {
    await newForm(page);
    await expect(page.getByLabel("Port")).toHaveValue("5432");
    await expect(page.getByLabel("Database", { exact: true })).toBeVisible();
    await expect(box(page, "SSL mode")).toHaveAttribute(
      "data-value",
      "require",
    );
    await page.getByLabel("User").fill("ro");
    await page.getByLabel("Database", { exact: true }).fill("shop");
    const tip = page.locator(".code--tip");
    await expect(tip).toContainText('CREATE ROLE "ro" LOGIN');
    await expect(tip).toContainText('GRANT CONNECT ON DATABASE "shop"');
  });

  test("pasting a postgres:// URL fills the form", async ({ page }) => {
    await newForm(page);
    await page.getByLabel("Host").focus();
    await page.evaluate(() => {
      const el = document.activeElement as HTMLInputElement;
      const data = new DataTransfer();
      data.setData(
        "text",
        "postgres://ro:pw@db.example.com:6432/shop?sslmode=verify-full",
      );
      el.dispatchEvent(
        new ClipboardEvent("paste", {
          clipboardData: data,
          bubbles: true,
          cancelable: true,
        }),
      );
    });
    await expect(page.getByLabel("Host")).toHaveValue("db.example.com");
    await expect(page.getByLabel("Port")).toHaveValue("6432");
    await expect(page.getByLabel("User")).toHaveValue("ro");
    await expect(page.getByLabel("Database", { exact: true })).toHaveValue(
      "shop",
    );
    await expect(box(page, "SSL mode")).toHaveAttribute(
      "data-value",
      "verify-full",
    );
  });

  test("a database is required, and the profile saves with its SSL mode", async ({
    page,
  }) => {
    await newForm(page);
    await page.getByLabel("Name").fill("pg");
    await page.getByLabel("User").fill("ro");
    await page.getByRole("button", { name: "Save", exact: true }).click();
    await expect(page.getByText("Enter a database.")).toBeVisible();
    // The message sits inside the label, so the name now starts with "Database".
    await page.getByLabel(/^Database/).fill("shop");
    await choose(page, "SSL mode", "disable");
    await page.getByRole("button", { name: "Save", exact: true }).click();
    await expect.poll(async () => (await saved(page))?.length).toBe(1);
    expect((await saved(page))[0].profile).toMatchObject({
      driver: "postgres",
      dbname: "shop",
      sslMode: "disable",
      tls: false,
      port: 5432,
    });
  });
});
